"""P1.0d packaging spike: minimal JobForge background agent.

Not app code. Exercises the lifecycle pieces the architecture depends on:
- per-user data dir under %LOCALAPPDATA% (known-folder API, not env strings)
- single instance via an OS byte-range lock (released by Windows on death)
- SQLite WAL + synchronous=FULL, agent_runs history, crash detection
- forward-only migration with VACUUM INTO backup first; refuse a newer DB (exit 4)
- IPC: FastAPI on 127.0.0.1:<ephemeral>, per-start bearer token, Host check,
  ipc.json written atomically into a run\\ dir restricted to the user's SID
- a "discovery" ticker every 5 s that honors a persisted pause flag
- CLI: --shutdown (used by the installer hook), --status, --restore <file>

Run (dev): python agent.py
"""
from __future__ import annotations

import asyncio
import ctypes
import json
import msvcrt
import os
import secrets
import socket
import sqlite3
import subprocess
import sys
import time
import urllib.request
import uuid
from ctypes import wintypes
from pathlib import Path

import build_info  # generated by build.ps1: VERSION, SCHEMA_VERSION
# Module level on purpose: with postponed annotations FastAPI resolves 'Request' from module
# globals; imported inside build_app it was treated as a query parameter (422 on /v1/shutdown).
from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse

PROTOCOL_VERSION = 1
CREATE_NO_WINDOW = 0x08000000


# ---------- paths ----------

def local_app_data() -> Path:
    # FOLDERID_LocalAppData {F1B32785-6FBA-4FCF-9D55-7B8E7F157091}
    class GUID(ctypes.Structure):
        _fields_ = [("Data1", wintypes.DWORD), ("Data2", wintypes.WORD), ("Data3", wintypes.WORD), ("Data4", ctypes.c_ubyte * 8)]
    u = uuid.UUID("F1B32785-6FBA-4FCF-9D55-7B8E7F157091")
    g = GUID(u.fields[0], u.fields[1], u.fields[2], (ctypes.c_ubyte * 8)(*u.bytes[8:]))
    p = ctypes.c_wchar_p()
    hr = ctypes.windll.shell32.SHGetKnownFolderPath(ctypes.byref(g), 0, None, ctypes.byref(p))
    if hr != 0:
        raise OSError(f"SHGetKnownFolderPath failed: {hr:#x}")
    path = Path(p.value)
    ctypes.windll.ole32.CoTaskMemFree(p)
    return path


ROOT = Path(os.environ["JOBFORGE_DATA_DIR"]) if os.environ.get("JOBFORGE_DATA_DIR") else local_app_data() / "JobForgeSpikeData"
DATA, LOGS, BACKUPS, RUN = ROOT / "data", ROOT / "logs", ROOT / "backups", ROOT / "run"
DB = DATA / "jobforge.db"
LOCK = RUN / "agent.lock"
IPC = RUN / "ipc.json"


def now_ms() -> int:
    return int(time.time() * 1000)


def log(event: str, **kw) -> None:
    LOGS.mkdir(parents=True, exist_ok=True)
    line = json.dumps({"ts": now_ms(), "pid": os.getpid(), "version": build_info.VERSION, "event": event, **kw})
    with open(LOGS / "agent.jsonl", "a", encoding="utf-8") as f:
        f.write(line + "\n")


# ---------- single instance ----------

class InstanceLock:
    def __init__(self, path: Path):
        self.path = path
        self.fh = None

    def try_acquire(self) -> bool:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.fh = open(self.path, "a+b")
        try:
            self.fh.seek(0)
            msvcrt.locking(self.fh.fileno(), msvcrt.LK_NBLCK, 1)
            return True
        except OSError:
            self.fh.close()
            self.fh = None
            return False

    def release(self) -> None:
        if self.fh:
            self.fh.seek(0)
            msvcrt.locking(self.fh.fileno(), msvcrt.LK_UNLCK, 1)
            self.fh.close()
            self.fh = None


def restrict_run_dir() -> str:
    """Remove inherited ACEs from run\\ and grant only the current user's SID."""
    out = subprocess.run(["whoami", "/user", "/fo", "csv", "/nh"], capture_output=True, text=True, creationflags=CREATE_NO_WINDOW)
    sid = out.stdout.strip().split(",")[-1].strip('"')
    r = subprocess.run(["icacls", str(RUN), "/inheritance:r", "/grant:r", f"*{sid}:(OI)(CI)F"],
                       capture_output=True, text=True, creationflags=CREATE_NO_WINDOW)
    if r.returncode != 0:
        raise OSError(f"icacls failed: {r.stdout} {r.stderr}")
    return sid


# ---------- database ----------

MIGRATIONS = {
    1: """
        CREATE TABLE agent_runs (id INTEGER PRIMARY KEY, pid INTEGER NOT NULL, version TEXT NOT NULL,
            started_at_ms INTEGER NOT NULL, stopped_at_ms INTEGER, stop_reason TEXT, heartbeat_at_ms INTEGER) STRICT;
        CREATE TABLE ticks (id INTEGER PRIMARY KEY, run_id INTEGER NOT NULL REFERENCES agent_runs(id), at_ms INTEGER NOT NULL) STRICT;
        CREATE TABLE settings (key TEXT PRIMARY KEY, value TEXT NOT NULL) STRICT;
        INSERT INTO settings VALUES ('discovery_paused', '0');
    """,
    2: """
        ALTER TABLE ticks ADD COLUMN note TEXT;
        INSERT INTO settings VALUES ('migrated_to_2_at_ms', CAST(strftime('%s','now') AS TEXT));
    """,
}


def connect() -> sqlite3.Connection:
    DATA.mkdir(parents=True, exist_ok=True)
    c = sqlite3.connect(DB, isolation_level=None, timeout=5)
    c.execute("PRAGMA journal_mode=WAL")
    c.execute("PRAGMA synchronous=FULL")
    c.execute("PRAGMA foreign_keys=ON")
    return c


def migrate(c: sqlite3.Connection) -> None:
    current = c.execute("PRAGMA user_version").fetchone()[0]
    target = build_info.SCHEMA_VERSION
    if current > target:
        log("db_newer_than_agent", db_version=current, agent_schema=target)
        sys.exit(4)
    if current == target:
        return
    if current > 0:
        BACKUPS.mkdir(parents=True, exist_ok=True)
        dest = BACKUPS / f"pre-migrate-v{current}-{time.strftime('%Y%m%d-%H%M%S')}.db"
        c.execute("VACUUM INTO ?", (str(dest),))
        chk = sqlite3.connect(dest).execute("PRAGMA integrity_check").fetchone()[0]
        log("pre_migrate_backup", path=str(dest), integrity=chk)
        if chk != "ok":
            sys.exit(5)
    for v in range(current + 1, target + 1):
        c.execute("BEGIN IMMEDIATE")
        try:
            # DDL is transactional in SQLite: a crash here leaves the old user_version intact
            for stmt in [s for s in MIGRATIONS[v].split(";") if s.strip()]:
                c.execute(stmt)
            c.execute(f"PRAGMA user_version = {v}")
            c.execute("COMMIT")
            log("migrated", to=v)
        except Exception:
            c.execute("ROLLBACK")
            raise


# ---------- agent ----------

class Agent:
    def __init__(self) -> None:
        self.c = connect()
        migrate(self.c)
        self.started = now_ms()
        orphans = self.c.execute("UPDATE agent_runs SET stopped_at_ms = heartbeat_at_ms, stop_reason = 'crash_recovered' "
                                 "WHERE stopped_at_ms IS NULL RETURNING id").fetchall()
        self.run_id = self.c.execute("INSERT INTO agent_runs (pid, version, started_at_ms, heartbeat_at_ms) VALUES (?,?,?,?) RETURNING id",
                                     (os.getpid(), build_info.VERSION, self.started, self.started)).fetchone()[0]
        log("agent_start", run_id=self.run_id, recovered_orphan_runs=[o[0] for o in orphans], db=str(DB),
            elevated=bool(ctypes.windll.shell32.IsUserAnAdmin()))
        self.token = secrets.token_hex(32)
        self.stop = asyncio.Event()
        self.stop_reason = "unknown"

    def paused(self) -> bool:
        return self.c.execute("SELECT value FROM settings WHERE key='discovery_paused'").fetchone()[0] == "1"

    async def ticker(self) -> None:
        while not self.stop.is_set():
            t = now_ms()
            if not self.paused():
                self.c.execute("INSERT INTO ticks (run_id, at_ms) VALUES (?,?)", (self.run_id, t))
            self.c.execute("UPDATE agent_runs SET heartbeat_at_ms=? WHERE id=?", (t, self.run_id))
            try:
                await asyncio.wait_for(self.stop.wait(), timeout=5)
            except asyncio.TimeoutError:
                pass

    def health(self) -> dict:
        return {"version": build_info.VERSION, "protocol_version": PROTOCOL_VERSION, "pid": os.getpid(),
                "schema": self.c.execute("PRAGMA user_version").fetchone()[0], "paused": self.paused(),
                "ticks_this_run": self.c.execute("SELECT count(*) FROM ticks WHERE run_id=?", (self.run_id,)).fetchone()[0],
                "uptime_s": round((now_ms() - self.started) / 1000), "run_id": self.run_id, "data_dir": str(ROOT)}

    def finish(self) -> None:
        self.c.execute("UPDATE agent_runs SET stopped_at_ms=?, stop_reason=? WHERE id=?", (now_ms(), self.stop_reason, self.run_id))
        log("agent_stop", reason=self.stop_reason)


def build_app(agent: Agent, port_holder: dict):
    app = FastAPI(docs_url=None, redoc_url=None, openapi_url=None)

    @app.middleware("http")
    async def guard(request: Request, call_next):
        if request.headers.get("host") != f"127.0.0.1:{port_holder['port']}":
            return JSONResponse({"error": "bad host"}, status_code=400)
        auth = request.headers.get("authorization", "")
        if not secrets.compare_digest(auth, f"Bearer {agent.token}"):
            return JSONResponse({"error": "unauthorized"}, status_code=401)
        return await call_next(request)

    # async def on purpose: FastAPI runs plain def handlers in a worker thread, and the SQLite
    # connection belongs to the event-loop thread (first spike run: every call returned 500).
    @app.get("/v1/health")
    async def health():
        return agent.health()

    @app.post("/v1/pause")
    async def pause():
        agent.c.execute("UPDATE settings SET value='1' WHERE key='discovery_paused'")
        log("discovery_paused")
        return agent.health()

    @app.post("/v1/resume")
    async def resume():
        agent.c.execute("UPDATE settings SET value='0' WHERE key='discovery_paused'")
        log("discovery_resumed")
        return agent.health()

    @app.post("/v1/shutdown")
    async def shutdown(request: Request):
        agent.stop_reason = request.query_params.get("reason", "requested")
        agent.stop.set()
        return {"stopping": True}

    return app


async def serve(agent: Agent) -> None:
    import uvicorn

    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    sock.bind(("127.0.0.1", 0))
    port = sock.getsockname()[1]
    port_holder = {"port": port}
    RUN.mkdir(parents=True, exist_ok=True)
    sid = restrict_run_dir()
    tmp = RUN / "ipc.json.tmp"
    tmp.write_text(json.dumps({"port": port, "token": agent.token, "pid": os.getpid(), "protocol_version": PROTOCOL_VERSION}), encoding="utf-8")
    os.replace(tmp, IPC)
    log("ipc_ready", port=port, run_dir_sid=sid)
    server = uvicorn.Server(uvicorn.Config(build_app(agent, port_holder), log_config=None, access_log=False, lifespan="off"))

    async def stopper():
        await agent.stop.wait()
        server.should_exit = True

    await asyncio.gather(server.serve(sockets=[sock]), agent.ticker(), stopper())


# ---------- CLI ----------

def read_ipc() -> dict | None:
    try:
        return json.loads(IPC.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def request(method: str, path: str, timeout: float = 3) -> dict:
    info = read_ipc()
    if not info:
        raise ConnectionError("no ipc.json")
    req = urllib.request.Request(f"http://127.0.0.1:{info['port']}{path}", method=method, data=b"" if method == "POST" else None,
                                 headers={"Authorization": f"Bearer {info['token']}"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read())


def cli_shutdown(reason: str) -> int:
    """Used by the installer hook: ask the running agent to stop, wait for its lock, kill as last resort."""
    log("cli_shutdown_begin", reason=reason)
    info = read_ipc()
    try:
        request("POST", f"/v1/shutdown?reason={reason}")
    except Exception as exc:
        log("cli_shutdown_request_failed", error=str(exc)[:200])
    lock = InstanceLock(LOCK)
    deadline = time.time() + 30
    while time.time() < deadline:
        if lock.try_acquire():
            lock.release()
            log("cli_shutdown_done", how="graceful_or_not_running")
            return 0
        time.sleep(0.5)
    if info:
        subprocess.run(["taskkill", "/PID", str(info["pid"]), "/F"], capture_output=True, creationflags=CREATE_NO_WINDOW)
        log("cli_shutdown_done", how="killed", pid=info["pid"])
    return 0


def cli_restore(path: str) -> int:
    lock = InstanceLock(LOCK)
    if not lock.try_acquire():
        print("agent is running; stop it first")
        return 3
    for suffix in ("", "-wal", "-shm"):
        p = Path(str(DB) + suffix)
        if p.exists():
            p.unlink()
    src = sqlite3.connect(path)
    dst = sqlite3.connect(DB)
    src.backup(dst)
    dst.close()
    src.close()
    log("restored", source=path)
    lock.release()
    return 0


def main() -> int:
    args = sys.argv[1:]
    if args[:1] == ["--shutdown"]:
        return cli_shutdown(args[1] if len(args) > 1 else "installer")
    if args[:1] == ["--status"]:
        print(json.dumps(request("GET", "/v1/health"), indent=2))
        return 0
    if args[:1] == ["--restore"]:
        return cli_restore(args[1])
    lock = InstanceLock(LOCK)
    if not lock.try_acquire():
        log("already_running")
        return 3
    agent = Agent()
    try:
        asyncio.run(serve(agent))
    finally:
        agent.finish()
        lock.release()
    return 0


if __name__ == "__main__":
    sys.exit(main())
